<h2>Број 7. М+S</h2>
<p>М+S  ознака која се сретнува кај зимските гуми означува дека гумата е констуирана за употреба во зимски услови, M = mud што значи кал, и S = snow што значи снег. Вакава ознака имаат и гумите кои се наменети за употреба во текот на сите 4 годишни времиња таканаречените  ALL SEASON гуми, но дополнително кај нив, наместо „ снегулка“ има четири симболи кои асоцираат на четирите годишни времиња.</p>
<h2>Број 8. Година на производство (DOT 1410)</h2>
<p>DOT 1410  – Го означува датумот на производство на гумата и е изразен во следната форма:</p>
<p>Во наведениов пример  14 означува дека е произведена  14-та недела од  (10)  2010 година.</p>
<p>Број 9. TWI (индикатор на потрошеност на шарата на  гумата) – покажува кога гумата треба да биде сменета</p>
<h2>“Run-Flat” гуми</h2>
<p>Овие гуми се дизајнирани да не го испуштаат воздухот, доколку се дупнат. Со тоа, овозможуваат возење со ограничена максимална брзина (до 90km/h), на растојание од 150 km до 300 km, во зависност од квалитетот и видот на гумата</p>
      
